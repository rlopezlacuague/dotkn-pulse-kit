// npm run contract:swift — writes swift/Sources/PulseKit/Contract.swift from src/contract.ts, so
// the Swift client and the TypeScript collector read the same values (a test asserts equality).
import { writeFileSync } from 'node:fs';
import { CONTRACT, EVENT_NAME } from '../src/contract.ts';
import { MAX_BATCH } from '../src/core/collector.ts';

export function swiftContract(): string {
  const q = (s: string) => JSON.stringify(s);
  return `// Generated by \`npm run contract:swift\` from src/contract.ts. Do not edit.
public enum PulseContract {
    public static let version = ${CONTRACT.version}
    public static let collector = ${q(CONTRACT.collector)}
    public static let eventName = ${q(EVENT_NAME.source)}
    public static let maxBatch = ${MAX_BATCH}
    public static let layout = ${q(CONTRACT.events.layout)}
}
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = new URL('../swift/Sources/PulseKit/Contract.swift', import.meta.url);
  writeFileSync(out, swiftContract());
  process.stdout.write(`wrote ${out.pathname}\n`);
}
