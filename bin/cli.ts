#!/usr/bin/env node
// dotkn-pulse-kit <command>
//   check <base-url>                       probe a deployed app against the contract (exit 1 on any deviation)
//   stamp --out <file.ts>                  write `export const PULSE_BUILD = {commit, builtAt}` (fails without a commit)
//   supabase --app <id> [--from-yaml <apps.yaml>]   print the pulse.metrics() migration
import { readFileSync, writeFileSync } from 'node:fs';
import { parse } from 'yaml';
import { checkContract } from '../src/check.ts';
import { stampBuild } from '../src/build-node.ts';
import { metricsMigration, type YamlMetric } from '../src/supabase.ts';
import { assertAppId } from '../src/contract.ts';

const [cmd, ...rest] = process.argv.slice(2);
const flag = (name: string) => {
  const i = rest.indexOf(`--${name}`);
  return i >= 0 ? rest[i + 1] : undefined;
};
const fail = (msg: string, code = 2): never => {
  process.stderr.write(`${msg}\n`);
  process.exit(code);
};
const USAGE = 'usage: dotkn-pulse-kit check <base-url> | stamp --out <file.ts> | supabase --app <id> [--from-yaml <apps.yaml>]';

try {
  if (cmd === 'check') {
    const base = rest[0] ?? fail(USAGE);
    const r = await checkContract(base);
    process.stdout.write(r.ok ? `ok ${base}: /health ok, /__build ${r.commit} built ${r.builtAt}\n` : `${r.failures.map((x) => `✖ ${x}`).join('\n')}\n`);
    process.exit(r.ok ? 0 : 1);
  } else if (cmd === 'stamp') {
    const out = flag('out') ?? fail(USAGE);
    const b = stampBuild();
    writeFileSync(out, `// Generated by dotkn-pulse-kit stamp at build time. Do not commit.\nexport const PULSE_BUILD = ${JSON.stringify(b)} as const;\n`);
    process.stdout.write(`stamped ${b.commit} at ${b.builtAt} -> ${out}\n`);
  } else if (cmd === 'supabase') {
    const app = assertAppId(flag('app') ?? fail(USAGE));
    const yamlPath = flag('from-yaml');
    let metrics: YamlMetric[] | undefined;
    if (yamlPath) {
      const doc = parse(readFileSync(yamlPath, 'utf8')) as { apps?: Array<{ id: string; supabase?: { metrics?: YamlMetric[] } }> };
      const entry = doc.apps?.find((a) => a.id === app) ?? fail(`no app "${app}" in ${yamlPath}`);
      metrics = entry.supabase?.metrics ?? [];
    }
    process.stdout.write(metricsMigration({ app, ...(metrics ? { metrics } : {}) }));
  } else fail(USAGE);
} catch (e) {
  fail((e as Error).message, 1);
}
